import { describe, expect, it } from 'vitest'

import { createGraph, describeGraph, every, latest, sample, watch } from '../src'
import { graphMarkdown } from '../src/testing'
import { shopGraph } from './fixtures'

describe('graphMarkdown', () => {
  it('lists a description as Markdown, with no diagram', () => {
    expect(graphMarkdown(describeGraph(shopGraph()))).toMatchInlineSnapshot(`
      "# \`shop\` graph

      Generated by \`describeGraph\`, description format 1. Do not edit.

      A \`state\` always holds a value, starting at build time; a \`value\` may be unwritten, unknown or failed; a \`stream\` delivers each write and holds nothing before its first. \`coalesces\` suppresses writes identical to the last record. \`expires\` marks a declared expiry extractor, not a TTL; a level's per-write expiry is not shown.

      A read is \`latest\` (a change schedules the reader), \`sample\` (read when something else schedules the reader; it schedules the reader itself only when the node becomes readable from unreadable), \`every\` (each write, in delivery order) or \`watch\` (the record, once per step that writes it or passes an expiry).

      Effect requests are \`every\` reads. An effect sample reads the current value when called; it creates no request, but a \`ready\` policy may use it to release queued work.

      ## Entry points

      - \`orders\`: source
      - \`price\`: source
      - \`tick\`: clock, every 1000 ms

      ## Nodes

      By id. Direct consumers list each reader once per read mode or effect role; aliases remain in Operators and Effects below. These are declared dependencies, not transitive paths. "None declared" does not imply the node is unused outside these declarations.

      | Node | Kind | Shape | Producer | Notes | Direct consumers |
      | --- | --- | --- | --- | --- | --- |
      | \`doubled\` | derived | state | map | coalesces | None declared |
      | \`ledger.total\` | derived | state | fold | coalesces | \`priced\` (latest)<br>\`doubled\` (latest)<br>\`chain.ship\` (effect sample) |
      | \`orders\` | occurrence | stream | source |  | \`ledger.total\` (every)<br>\`log\` (effect request) |
      | \`price\` | level | value | source |  | \`priced\` (sample) |
      | \`priced\` | derived | value | map | coalesces, expires | \`watcher\` (watch) |
      | \`receipts\` | derived | stream | emitted by \`ledger.total\` |  | \`chain.ship\` (effect request)<br>\`chain.audit\` (effect request)<br>\`report\` (effect request) |
      | \`shipped\` | derived | stream | result of \`chain.ship\` |  | \`ledger.total\` (every) |
      | \`tick\` | clock | stream | clock, every 1000 ms |  | \`ledger.total\` (every) |
      | \`watcher\` | derived | state | fold | coalesces | None declared |

      ## Operators

      In evaluation order. A fold's \`afterInputs\` runs once after that evaluation's inputs.

      - \`ledger.total\`: fold, with afterInputs
        - reads \`order\` from \`orders\`: every
        - reads \`shipped\` from \`shipped\`: every
        - reads \`tick\` from \`tick\`: every
        - emits \`receipts\`
      - \`priced\`: map
        - reads \`total\` from \`ledger.total\`: latest
        - reads \`price\` from \`price\`: sample
      - \`doubled\`: map
        - reads \`total\` from \`ledger.total\`: latest
      - \`watcher\`: fold
        - reads \`priced\` from \`priced\`: watch

      ## Effects

      In dispatch order. Omitted results mean no declared graph-result stream, not no external side effects. Omitted policies mean none of the optional policies are declared; listed policies show presence, not callback decisions.

      - \`chain.ship\`: lane \`venue\`
        - requests \`receipt\` from \`receipts\`
        - samples \`total\` from \`ledger.total\`
        - results: \`shipped\`
        - policies: \`sequence\`, \`ready\`
      - \`chain.audit\`: lane \`venue\`
        - requests \`receipt\` from \`receipts\`
      - \`report\`: lane \`venue#2\`
        - requests \`receipt\` from \`receipts\`
        - policies: \`latestOnly\`
      - \`log\`: lane \`default\`
        - requests \`order\` from \`orders\`
        - policies: \`finishOnStop\`

      ## Lanes

      In the order the runner serves them. Effects share a lane only when they share its declaration.

      | Lane | Concurrency | Queue | Budget | Effects |
      | --- | --- | --- | --- | --- |
      | \`venue\` | 2 | 8 | 5 per 1000 ms | \`chain.ship\`, \`chain.audit\` |
      | \`venue#2\` | 1 | 1 | none | \`report\` |
      | \`default\` | unbounded | 1024 | none | \`log\` |

      ## Recovery

      After a failure outside the recovery scope, only these members run, to wind the scope down; then the runner stops. A failure inside the scope stops the runner at once. Members by id:

      - \`chain.audit\`
      - \`chain.ship\`
      "
    `)
  })

  it('lists only source and clock entry points, including clock periods', () => {
    const markdown = graphMarkdown(describeGraph(shopGraph()))
    expect(markdown).toContain(
      '## Entry points\n\n- `orders`: source\n- `price`: source\n- `tick`: clock, every 1000 ms\n\n## Nodes'
    )
  })

  it('indexes direct consumers by mode and role while preserving every alias in the ordered listings', () => {
    const g = createGraph('aliases')
    const input = g.occurrences<number>('input')
    const result = g.node<number>('result')
    const reader = g.fold('reader', {
      reads: { first: every(input), second: every(input), record: watch(input) },
      initial: 0,
      applyInput: state => ({ state })
    })
    g.map('sampled', {
      reads: { quiet: sample(reader), active: latest(reader) },
      compute: ({ active }) => active
    })
    g.effect('sink', {
      requests: { first: every(input), second: every(input) },
      samples: { current: reader },
      results: result,
      handle: () => {}
    })
    g.fold('feedback', {
      reads: { answer: every(result) },
      initial: 0,
      applyInput: state => ({ state })
    })
    const markdown = graphMarkdown(describeGraph(g.build()))
    expect(markdown).toContain(
      '| `input` | occurrence | stream | source |  | `reader` (every)<br>`reader` (watch)<br>`sink` (effect request) |'
    )
    expect(markdown).toContain(
      '| `reader` | derived | state | fold | coalesces | `sampled` (sample)<br>`sampled` (latest)<br>`sink` (effect sample) |'
    )
    expect(markdown).toContain(
      '| `result` | derived | stream | result of `sink` |  | `feedback` (every) |'
    )
    expect(markdown).toContain('| `sampled` | derived | state | map | coalesces | None declared |')
    expect(markdown).toContain('does not imply the node is unused')
    expect(markdown).toContain(
      '  - reads `first` from `input`: every\n  - reads `second` from `input`: every\n  - reads `record` from `input`: watch'
    )
    expect(markdown).toContain(
      '  - requests `first` from `input`\n  - requests `second` from `input`\n  - samples `current` from `reader`'
    )
  })

  it('renders an empty graph without inventing inputs or recovery members', () => {
    const markdown = graphMarkdown(describeGraph(createGraph('empty').build()))
    expect(markdown).toContain('## Entry points\n\nNo source or clock nodes.')
    expect(markdown).toContain('## Recovery\n\nNo recovery scope.')
    expect(markdown).not.toContain('## Scopes')
    expect(markdown).not.toContain('undefined')
    expect(markdown).not.toContain('```mermaid')
  })

  it('omits absent effect results and policies but keeps declared ones', () => {
    const markdown = graphMarkdown(describeGraph(shopGraph()))
    expect(markdown).not.toContain('results: none')
    expect(markdown).not.toContain('policies: none')
    expect(markdown).toContain('  - results: `shipped`\n  - policies: `sequence`, `ready`')
    expect(markdown).toContain(
      '- `chain.audit`: lane `venue`\n  - requests `receipt` from `receipts`\n- `report`:'
    )
    expect(markdown).toContain('Omitted results mean no declared graph-result stream')
    expect(markdown).toContain('Omitted policies mean none of the optional policies are declared')
  })

  it('adds fixture provenance only when the caller supplies its links', () => {
    const description = describeGraph(shopGraph())
    const generic = graphMarkdown(description)
    expect(generic).not.toContain('listing fixture')
    expect(generic).not.toContain('graph-listing -u')
    const contextual = graphMarkdown(description, {
      declaration: './src/graph.ts',
      fixture: './test/graph-listing.test.ts',
      spec: '../../framework/engine/SPEC.md'
    })
    expect(contextual).toContain('[listing fixture](./test/graph-listing.test.ts)')
    expect(contextual).toContain('[declaration](./src/graph.ts)')
    expect(contextual).toContain('[engine specification](../../framework/engine/SPEC.md)')
    expect(contextual).toContain('not a deployed configuration')
    expect(contextual).toContain('bunx vitest run graph-listing -u')
  })
})
